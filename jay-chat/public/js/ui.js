const AVATAR_COLORS = [
  ['#5b8cff', '#8a5cff'], ['#ff6b8a', '#ff9a5b'], ['#2fd57c', '#2fa8d5'],
  ['#ffb75b', '#ff8a5b'], ['#8a5cff', '#d05cff'], ['#2fd5c8', '#5b8cff'],
  ['#ff5b6e', '#8a5cff'], ['#5bc8ff', '#2fd57c'],
];
function avatarColor(name) {
  let h = 0;
  for (const c of String(name || '')) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return AVATAR_COLORS[h % AVATAR_COLORS.length];
}
function renderAvatar(user, cls) {
  const wrap = el('div', 'avatar-wrap');
  const av = el('div', 'avatar ' + (cls || ''));
  if (user && user.avatar) {
    av.innerHTML = `<img src="${user.avatar}" alt="">`;
  } else {
    const name = (user && (user.remark || user.username)) || '?';
    const [c1, c2] = avatarColor(name);
    av.style.background = `linear-gradient(135deg, ${c1}, ${c2})`;
    av.textContent = name[0] || '?';
  }
  wrap.appendChild(av);
  // 官方认证蓝色✔
  if (user && user.isOfficial) {
    wrap.appendChild(el('span', 'official-badge', '<svg viewBox="0 0 24 24"><path d="M4 12.5l5 5L20 6.5" stroke="#fff" stroke-width="4.5" fill="none" stroke-linecap="round" stroke-linejoin="round"/></svg>'));
  }
  // 在线状态
  if (user && user.showOnline) {
    const dot = el('i', 'online-dot' + (user.online ? '' : ' off'));
    wrap.appendChild(dot);
  }
  return wrap;
}

