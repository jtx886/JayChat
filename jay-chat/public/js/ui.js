// ===== 弹窗 =====
function openModal(contentEl, { onClose } = {}) {
  const mask = el('div', 'modal-mask');
  const modal = el('div', 'modal glass', '');
  modal.appendChild(contentEl);
  mask.appendChild(modal);
  $('#modal-root').appendChild(mask);
  const close = () => {
    mask.classList.add('closing');
    setTimeout(() => mask.remove(), 220);
    if (onClose) onClose();
  };
  mask.addEventListener('click', (e) => { if (e.target === mask) close(); });
  return { close, mask, modal };
}

function confirmDialog(title, text, danger) {
  return new Promise((resolve) => {
    const box = el('div');
    box.innerHTML = `<div class="modal-title">${title}</div><p style="font-size:14px;color:var(--text-2);line-height:1.6">${text}</p>`;
    const actions = el('div', 'modal-actions');
    const no = el('button', 'btn-ghost', '取消');
    const yes = el('button', 'btn-primary' + (danger ? ' btn-danger' : ''), '确定');
    no.onclick = () => { m.close(); resolve(false); };
    yes.onclick = () => { m.close(); resolve(true); };
    actions.append(no, yes);
    box.appendChild(actions);
    const m = openModal(box);
  });
}

