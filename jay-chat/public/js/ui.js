function viewMedia(src, isVideo, tip) {
  const root = $('#media-viewer');
  root.innerHTML = '';
  root._onclose = null;
  root.classList.remove('hidden');
  const close = el('button', 'viewer-close', '✕');
  close.onclick = () => { root.classList.add('hidden'); if (root._onclose) root._onclose(); };
  root.appendChild(close);
  let media;
  if (isVideo) {
    media = el('video');
    media.src = src; media.controls = true; media.autoplay = true; media.playsInline = true;
  } else {
    media = el('img'); media.src = src;
  }
  root.appendChild(media);
  if (tip) root.appendChild(el('div', 'viewer-tip', tip));
  root.onclick = (e) => { if (e.target === root) close.onclick(); };
  return { close: close.onclick };
}

// ===== 好友选择弹窗 =====
function pickFriendsModal({ multiple = true, excludeIds = [], title = '选择好友', onDone, selectedTitle = '确定' }) {
  API.get('/api/friends').then(({ friends }) => {
    const list = friends.filter((f) => !excludeIds.includes(f.id));
    const box = el('div');
    box.innerHTML = `<div class="modal-title">${title}<button class="modal-close">✕</button></div>`;
    if (!list.length) {
      box.appendChild(el('p', '', '<div class="empty"><p>暂无好友可选择</p></div>'));
    } else {
      const searchBar = el('div', 'search-bar', '<svg viewBox="0 0 24 24"><path d="M15.5 14h-.79l-.28-.27a6.5 6.5 0 10-.7.7l.27.28v.79l5 4.99L20.49 19l-4.99-5zm-6 0A4.5 4.5 0 1114 9.5 4.5 4.5 0 019.5 14z" fill="currentColor"/></svg>');
      const inp = el('input'); inp.placeholder = '搜索好友';
      inp.oninput = () => render(inp.value.trim());
      searchBar.appendChild(inp);
      box.appendChild(searchBar);
      const wrap = el('div', 'pick-list');
      box.appendChild(wrap);
      const picked = new Set();
      function render(q) {
        wrap.innerHTML = '';
        for (const f of list) {
          if (q && !(f.remark || f.username).includes(q)) continue;
          const item = el('div', 'pick-item' + (picked.has(f.id) ? ' picked' : ''));
          item.appendChild(renderAvatar({ ...f, showOnline: true, remark: undefined }));
          item.appendChild(el('div', 'item-main', `<div class="item-title">${esc(f.remark || f.username)}</div>`));
          const check = el('div', 'pick-check', '<svg viewBox="0 0 24 24"><path d="M5 13l4 4L19 7" stroke="#fff" stroke-width="3.5" fill="none" stroke-linecap="round" stroke-linejoin="round"/></svg>');
          item.appendChild(check);
          item.onclick = () => {
            if (picked.has(f.id)) picked.delete(f.id);
            else {
              if (!multiple) picked.clear();
              picked.add(f.id);
            }
            item.classList.toggle('picked', picked.has(f.id));
          };
          wrap.appendChild(item);
        }
      }
      render('');
      const actions = el('div', 'modal-actions');
      const btn = el('button', 'btn-primary', `${selectedTitle}${multiple && picked.size ? ` (${picked.size})` : ''}`);
      const refresh = () => { btn.textContent = `${selectedTitle}${multiple && picked.size ? ` (${picked.size})` : ''}`; };
      wrap.addEventListener('click', (e) => { if (e.target.closest('.pick-item')) setTimeout(refresh, 0); });
      btn.onclick = () => {
        if (!picked.size) return toast('请先选择好友', 'error');
        m.close();
        onDone([...picked]);
      };
      actions.appendChild(btn);
      box.appendChild(actions);
    }
    const m = openModal(box);
    box.querySelector('.modal-close').onclick = () => m.close();
  });
}

// ===== 时长选择（禁言/封禁自定义时间） =====
function durationModal(title, unit) {
  return new Promise((resolve) => {
    const box = el('div');
    box.innerHTML = `<div class="modal-title">${title}<button class="modal-close">✕</button></div>
      <p style="font-size:13px;color:var(--text-2)">请选择${unit}时长（也可自定义分钟数）</p>`;
    const row = el('div', 'dur-row');
    const presets = [['10分钟', 10], ['1小时', 60], ['6小时', 360], ['1天', 1440], ['7天', 10080], ['30天', 43200]];
    let selected = null;
    for (const [label, mins] of presets) {
      const b = el('button', 'dur-opt', label);
      b.onclick = () => { selected = mins; $$('.dur-opt', row).forEach((x) => x.classList.remove('active')); b.classList.add('active'); };
      row.appendChild(b);
    }
    box.appendChild(row);
    const custom = el('input', 'inline-input');
    custom.type = 'number'; custom.min = 1; custom.placeholder = '自定义分钟数';
    custom.style.width = '100%';
    box.appendChild(custom);
    const actions = el('div', 'modal-actions');
    const no = el('button', 'btn-ghost', '取消');
    const yes = el('button', 'btn-primary', '确定');
    no.onclick = () => { m.close(); resolve(null); };
    yes.onclick = () => {
      let mins = selected;
      if (custom.value) mins = Number(custom.value);
      if (!mins || mins <= 0) return toast('请选择或输入有效的时长', 'error');
      m.close();
      resolve(mins);
    };
    actions.append(no, yes);
    box.appendChild(actions);
    const m = openModal(box);
    box.querySelector('.modal-close').onclick = () => { m.close(); resolve(null); };
  });
}

// HTML 转义
function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

// 长按
function onLongPress(target, handler) {
  let timer = null;
  const start = (e) => {
    timer = setTimeout(() => { timer = null; handler(e); }, 480);
  };
  const cancel = () => { if (timer) { clearTimeout(timer); timer = null; } };
  target.addEventListener('touchstart', start, { passive: true });
  target.addEventListener('touchend', cancel);
  target.addEventListener('touchmove', cancel);
  target.addEventListener('touchcancel', cancel);
  target.addEventListener('mousedown', start);
  ['mouseup', 'mouseleave', 'mousemove'].forEach((ev) => target.addEventListener(ev, cancel));
  target.addEventListener('contextmenu', (e) => { e.preventDefault(); handler(e); });
}

